"""Check pinned packages and generate the Claude mirror; standard library only."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys


def safe_path(root, relative):
    """Reject traversal and symlink ancestors before reading or writing."""
    if not re.fullmatch(r"[a-zA-Z0-9_./-]+", relative):
        raise ValueError(f"Unsafe path: {relative}")
    parts = relative.split("/")
    if any(part in ("", ".", "..") for part in parts):
        raise ValueError(f"Unsafe path: {relative}")
    current = root.resolve()
    for part in parts:
        current = current / part
        if current.is_symlink() or (hasattr(current, "is_junction") and current.is_junction()):
            raise ValueError(f"Link is not allowed: {relative}")
    if not current.resolve().is_relative_to(root.resolve()):
        raise ValueError(f"Path escapes root: {relative}")
    return current


def inventory(root, relative):
    folder = safe_path(root, relative)
    if not folder.exists():
        return {}
    result = {}
    for path in folder.rglob("*"):
        rel = path.relative_to(root).as_posix()
        checked = safe_path(root, rel)
        if checked.is_file():
            result[checked.relative_to(folder).as_posix()] = checked
    return result


def read_json(root, path):
    return json.loads(safe_path(root, path).read_text(encoding="utf-8-sig"))


def verify_source(root):
    names = []
    hash_count = 0
    for filename, count in [("superpowers-source.json", 15), ("ui-skills-source.json", 2)]:
        manifest = read_json(root, ".agents/" + filename)
        skills, hashes = manifest["skills"], manifest["sha256"]
        if len(skills) != count or len(set(skills)) != count:
            raise ValueError(f"Unexpected package count: {filename}")
        for skill in skills:
            if not re.fullmatch(r"[a-z0-9-]+", skill):
                raise ValueError(f"Invalid skill name: {skill}")
            prefix = f".agents/skills/{skill}/"
            actual = {prefix + path for path in inventory(root, prefix.rstrip("/"))}
            expected = {path for path in hashes if path.startswith(prefix)}
            if actual != expected or prefix + "SKILL.md" not in expected:
                raise ValueError(f"Unmanifested or missing package files: {skill}")
        for relative, expected in hashes.items():
            if not relative.startswith(".agents/") or not re.fullmatch(r"[a-f0-9]{64}", expected):
                raise ValueError(f"Invalid hash entry: {relative}")
            data = safe_path(root, relative).read_bytes()
            if hashlib.sha256(data).hexdigest() != expected:
                raise ValueError(f"Hash mismatch: {relative}")
            hash_count += 1
        names.extend(skills)
    specialists = read_json(root, ".agents/specialists.json")["skills"]
    if len(specialists) != 7 or any(not re.fullmatch(r"formauto-[a-z0-9-]+", x) for x in specialists):
        raise ValueError("Expected seven project specialists")
    names.extend(specialists)
    if len(set(names)) != 24:
        raise ValueError("Duplicate package names")
    files = inventory(root, ".agents/skills")
    actual_names = {path.split("/")[0] for path in files}
    if actual_names != set(names):
        raise ValueError("Active skill inventory differs from manifests/specialists")
    for name in names:
        body = safe_path(root, f".agents/skills/{name}/SKILL.md").read_text(encoding="utf-8-sig")
        match = re.match(r"---\r?\n(.*?)\r?\n---", body, re.S)
        if not match or not re.search(r"^name:\s*" + re.escape(name) + r"\s*$", match[1], re.M):
            raise ValueError(f"Missing or mismatched skill name: {name}")
        if not re.search(r"^description:\s*\S", match[1], re.M):
            raise ValueError(f"Missing description: {name}")
    return files, hash_count


def check(root, sync=False):
    source, hash_count = verify_source(root)
    mirror = inventory(root, ".claude/skills")
    extra = mirror.keys() - source.keys()
    if extra:
        raise ValueError("Unexpected mirror files; preserve and resolve explicitly: " + ", ".join(sorted(extra)))
    # Preflight every target before mutation. --sync never deletes unknown work.
    targets = {path: safe_path(root, ".claude/skills/" + path) for path in source}
    drift = [path for path in source if path not in mirror or source[path].read_bytes() != mirror[path].read_bytes()]
    if drift and not sync:
        raise ValueError(f"Mirror drift in {len(drift)} files; inspect, then run --sync if authorized")
    for relative in drift:
        target = targets[relative]
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(source[relative].read_bytes())
    # Verify the generated bytes rather than treating writes as proof.
    if sync:
        check(root, sync=False)
    return {"skills": 24, "pinnedHashEntries": hash_count, "mirroredFiles": len(source), "syncedFiles": len(drift)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--check", action="store_true")
    group.add_argument("--sync", action="store_true", help="Regenerate known mirror files after authorized source changes")
    args = parser.parse_args()
    try:
        print(json.dumps(check(Path(__file__).resolve().parents[1], sync=args.sync)))
    except (ValueError, KeyError, OSError, TypeError) as error:
        print(str(error), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
